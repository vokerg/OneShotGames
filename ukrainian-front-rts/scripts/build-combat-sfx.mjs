#!/usr/bin/env node
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCombatSfxOutputs, serializeCombatSfxManifest } from './lib/combat-sfx-generator.mjs';
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputRoot = resolve(projectRoot, 'assets/audio/combat');
const check = process.argv.includes('--check');
const { manifest, banks } = buildCombatSfxOutputs();
const expected = new Map([['manifest.json', Buffer.from(serializeCombatSfxManifest(manifest))], ...banks.map((bank) => [bank.path, bank.wav])]);
if (check) {
  const failures = [];
  for (const [name, content] of expected) {
    try { const current = await readFile(resolve(outputRoot, name)); if (!current.equals(content)) failures.push(`${name}: generated bytes differ`); }
    catch (error) { failures.push(`${name}: ${error.code === 'ENOENT' ? 'missing' : error.message}`); }
  }
  if (failures.length) { for (const failure of failures) console.error(`[combat-sfx] ${failure}`); process.exitCode = 1; }
  else console.log(`[combat-sfx] ${banks.length} banks and manifest match deterministic generation.`);
} else {
  await mkdir(outputRoot, { recursive: true });
  for (const [name, content] of expected) await writeFile(resolve(outputRoot, name), content);
  console.log(`[combat-sfx] wrote ${banks.length} PCM WAV banks containing ${manifest.assets.length} original cues.`);
}
