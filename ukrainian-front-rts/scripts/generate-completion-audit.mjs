import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const completedRoot = join(root, 'tasks', 'completed');
const outputFlag = process.argv.indexOf('--output');
const output = resolve(root, outputFlag >= 0 ? process.argv[outputFlag + 1] : 'artifacts/completion-evidence-audit.md');
const levels = ['RELEASE_VERIFIED', 'PLAYER_VERIFIED', 'RUNTIME_INTEGRATED', 'CONTRACT_COMPLETE'];
const files = (await readdir(completedRoot)).filter((name) => /^UFR-\d+\.md$/.test(name)).sort();
const rows = [];
const missing = [];

for (const file of files) {
  const text = await readFile(join(completedRoot, file), 'utf8');
  const id = file.replace('.md', '');
  const level = levels.find((candidate) => text.includes(candidate)) || 'UNCLASSIFIED';
  if (level === 'UNCLASSIFIED') missing.push(id);
  const runtime = /runtime|assembled|integration/i.test(text) ? 'mentioned' : 'not recorded';
  const browser = /browser|playtest|mission/i.test(text) ? 'mentioned' : 'not recorded';
  const save = /save|migration|serializ/i.test(text) ? 'mentioned' : 'not recorded';
  const ai = /\bAI\b|computer opponent|planner/i.test(text) ? 'mentioned' : 'not recorded';
  const limitations = /unavailable|not run|could not|limitation/i.test(text) ? 'yes' : 'no';
  rows.push(`| ${id} | ${level} | ${runtime} | ${browser} | ${save} | ${ai} | ${limitations} |`);
}

const markdown = `# Completion evidence audit\n\nGenerated by \`scripts/generate-completion-audit.mjs\` from the assembled checkout. This inventory is diagnostic: “mentioned” means the completion record contains evidence or limitation language for that dimension, not that the dimension passed.\n\n- Completion markers: ${files.length}\n- Explicit evidence level: ${files.length - missing.length}\n- Missing evidence level: ${missing.length}${missing.length ? ` (${missing.join(', ')})` : ''}\n\n| Task | Highest recorded level | Runtime composition | Browser/player | Save implications | AI use | Limitations recorded |\n| --- | --- | --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`;
await mkdir(dirname(output), { recursive: true });
await writeFile(output, markdown);
console.log(`[completion-audit] wrote ${files.length} marker(s) to ${output}`);
if (missing.length) {
  console.error(`[completion-audit] ${missing.length} marker(s) lack an explicit evidence level.`);
  process.exitCode = 1;
}
